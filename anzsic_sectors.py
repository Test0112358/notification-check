# anzsic_sectors.py
# M&A Sector mapping for ANZSIC 2006 (Revision 2.0) codes
# Custom mapping designed for at-a-glance M&A deal reporting
# Maps Division (letter), Subdivision (2-digit), Group (3-digit)
# and Class (4-digit) codes to 25 distinct M&A sector labels
#
# Design principles:
#   - Mining sub-types (iron, gold, gravel) → single "Mining" label
#   - Financial services split into 7 sub-sectors including Superannuation
#   - Healthcare split into Hospitals / Medical / Dental / Aged Care / Pharmacy
#   - Technology separated from Telecommunications and from Media
#   - Automotive retail separated from general retail
#   - Fuel retail separated (Ampol-type deals)
#   - Oil & Gas and Coal separated from broader Mining
#   - Veterinary separated from Professional Services
#   - Gambling separated from broader Arts and Recreation
#
# Usage in scraper.py:
#   from anzsic_sectors import get_ma_sector
#   sector = get_ma_sector("6330")  → "Superannuation"
#   sector = get_ma_sector("6322")  → "General Insurance"
#   sector = get_ma_sector("K")     → "Financial and Insurance Services" (fallback)

