def get_ma_sector(anzsic_code: str) -> str:
    """
    Map an ANZSIC code to an M&A sector label.

    Tries the code as-is first (handles 4-digit class codes), then
    falls back progressively to 3-digit group, 2-digit subdivision,
    and 1-character division, so partial codes still resolve.

    Returns "Unknown / Other" if the code is not recognised.
    """
    if not anzsic_code:
        return ""

    code = str(anzsic_code).strip()

    # Direct lookup (handles all levels: letter, 2-, 3-, 4-digit)
    if code in ANZSIC_TO_MA_SECTOR:
        return ANZSIC_TO_MA_SECTOR[code]

    # Progressive fallback for 4-digit class codes
    if len(code) == 4 and code.isdigit():
        if code[:3] in ANZSIC_TO_MA_SECTOR:
            return ANZSIC_TO_MA_SECTOR[code[:3]]
        if code[:2] in ANZSIC_TO_MA_SECTOR:
            return ANZSIC_TO_MA_SECTOR[code[:2]]

    return "Unknown / Other"


def get_ma_sectors_for_entry(anzsic_codes_field: str) -> list[str]:
    if not anzsic_codes_field:
        return []
    import re
    sectors = []
    seen = set()
    for chunk in str(anzsic_codes_field).split(";"):
        # Extract leading digits only (e.g. "1852 Cosmetic..." -> "1852")
        m = re.match(r"\s*(\d+)", chunk)
        if not m:
            continue
        sector = get_ma_sector(m.group(1))
        if sector and sector != "Unknown / Other" and sector not in seen:
            sectors.append(sector)
            seen.add(sector)
    return sectors
